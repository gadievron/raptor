#!/usr/bin/env python3
"""Generate thin Codex adapters without copying maintained Claude procedures."""
import argparse
import json
from pathlib import Path
import re
import sys
import tomllib

import yaml

ROOT = Path(__file__).resolve().parents[1]
MARKER = 'Generated by scripts/sync_codex_commands.py; edit the source procedure instead.'
ROLE_BLOCK = re.compile(r'^developer_instructions\s*=\s*(?P<quote>"""|\'\'\').*?(?P=quote)', re.M | re.S)


def rendered(root):
    result = {}
    commands = sorted((root / '.claude/commands').glob('*.md'))
    if not commands:
        raise ValueError('No source commands found')
    for source in commands:
        metadata = yaml.safe_load(source.read_text().split('---', 2)[1])
        name = 'source-command-' + source.stem
        description = f"RAPTOR /{source.stem} workflow: {metadata['description'].strip()}"
        body = f'''---
name: {name}
description: {json.dumps(description)}
---
<!-- {MARKER} -->

Read [the Codex adapter guide](../../../docs/codex-command-compatibility.md),
then read and follow [the maintained /{source.stem} procedure](../../commands/{source.name}).
Resolve its relative references from that source document, not this adapter.
Load only the modes and supporting documents needed for the user's request.
'''
        if source.stem == 'commands':
            body += '''\nFor Codex, list the available `source-command-*` skills as `$source-command-<name>`
with the source descriptions. Honor source `exclude_from_listing` metadata;
include all other commands, including tune. Do not advertise native slash registration.
'''
        if source.stem == 'create-skill':
            body += '''\nFor a new Codex skill, use a lowercase-hyphen folder containing `SKILL.md`
with YAML `name` and `description`, rather than a bare Markdown file.
Keep the source workflow's review and approval requirements.
'''
        result[Path('.claude/skills') / name / 'SKILL.md'] = body
    sources = {}
    for source in (root / '.claude/agents').glob('*.md'):
        header = source.read_text().split('---', 2)[1]
        match = re.search(r'^name:\s*([^\n]+)', header, re.M)
        if not match:
            raise ValueError(f'Missing role name: {source}')
        name = match[1].strip().strip('\"\'')
        if name in sources:
            raise ValueError(f'Duplicate role: {name}')
        sources[name] = source
    seen = set()
    for path in sorted((root / '.codex/agents').glob('*.toml')):
        original = path.read_text()
        name = tomllib.loads(original)['name']
        if name in seen:
            raise ValueError(f'Duplicate native role: {name}')
        seen.add(name)
        source = sources[name]
        instructions = f'''{MARKER}
Before doing this role's work, read docs/codex-command-compatibility.md and
.claude/agents/{source.name} relative to the RAPTOR repository root.
The latter is the maintained role procedure. Follow its stages, gates,
artifacts, constraints, and handoffs; load referenced resources as needed.
Claude frontmatter is not a Codex permission or hook configuration. If a
required capability or isolation control is unavailable, report the gap and
stop the affected step instead of assuming the control exists.
'''
        replacement = 'developer_instructions = """\n' + instructions + '"""'
        updated, count = ROLE_BLOCK.subn(lambda _: replacement, original)
        if count != 1:
            raise ValueError(f'Expected one instruction block: {path}')
        result[path.relative_to(root)] = updated
    if set(sources) != seen:
        raise ValueError(f'Unmapped source roles: {sorted(set(sources) - seen)}')
    return result


def sync(root, write=False):
    expected = rendered(root)
    stale = []
    for relative, content in expected.items():
        path = root / relative
        if not path.exists() or path.read_text() != content:
            stale.append(relative)
            if write:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    obsolete = [p.relative_to(root) for p in
                (root / '.claude/skills').glob('source-command-*/SKILL.md')
                if p.relative_to(root) not in expected]
    return stale, obsolete


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--write', action='store_true')
    args = parser.parse_args()
    try:
        stale, obsolete = sync(ROOT, args.write)
    except (OSError, ValueError, KeyError, yaml.YAMLError) as exc:
        print(exc, file=sys.stderr)
        return 1
    for path in stale:
        print(f"{'Updated' if args.write else 'Out of date'}: {path}")
    for path in obsolete:
        print(f'Review obsolete adapter manually: {path}')
    return int(bool(obsolete or (stale and not args.write)))


if __name__ == '__main__':
    sys.exit(main())
